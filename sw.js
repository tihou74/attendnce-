/* =============================================================================
   عاملٌ خِدميٌّ لا يخدم شيئًا — وظيفتُه أن يُلغي نفسَه.
   -----------------------------------------------------------------------------
   ⚠️⚠️⚠️ لماذا ملفٌّ هنا بدل حذفِه؟

   هواتفُ الموظفين تحمل عاملًا خِدميًّا مسجَّلًا على هذا العنوانِ القديم، وهو
   يحفظ سبعَ صفحاتٍ في ذاكرتِه. فلو بقي كما كان، لظلّ جهازٌ يُقدّم نسخةً قديمةً
   من التطبيقِ من عنوانٍ لم يبقَ فيه تطبيق.

   وحذفُ الملفِّ يُلغي التسجيلَ أيضًا (المتصفّحُ يُلغيه عند 404)، لكنّه يفعل ذلك
   **بلا ترتيب**: لا يُمحى ما في الذاكرة، ولا تُحدَّث النوافذُ المفتوحة. فالصريحُ
   أوضحُ من المسكوتِ عنه، ولا يترك المتصفّحاتَ تختلف في تأويلِه.

   ⚠️ وما يفعله هذا الملفُّ بالترتيب:
     1) يأخذ مكانَ القديمِ فورًا بـskipWaiting (ولا ينتظر إغلاقَ التبويبات).
     2) يمحو **كلَّ** ذاكرةِ هذا الأصل.
     3) يُلغي تسجيلَ نفسِه.
     4) يُعيد تحميلَ كلِّ نافذةٍ مفتوحة، فتصل إلى صفحةِ التحويل.

   ⚠️ ولا يعترض أيَّ طلب: لا `fetch` هنا بقصد. أيُّ اعتراضٍ من عاملٍ يُلغي نفسَه
   قد يُقدّم نسخةً محفوظةً في اللحظةِ التي نريد فيها الشبكةَ بالذات.
   ============================================================================= */

self.addEventListener('install', (event) => {
    event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
    event.waitUntil((async () => {
        // 1) تُمحى كلُّ الذاكرة — لا استثناءَ، فلا شيءَ هنا يُراد حفظُه.
        try {
            const names = await caches.keys();
            await Promise.all(names.map(n => caches.delete(n)));
        } catch (e) { /* يُكمل على أيِّ حال: الإلغاءُ أهمُّ من المحو */ }

        // 2) يُلغي تسجيلَ نفسِه.
        try { await self.registration.unregister(); } catch (e) { /* تجاهل */ }

        // 3) ثم تُعاد النوافذُ المفتوحةُ إلى الشبكة، فتجد صفحةَ التحويل.
        //    ⚠️ بعد الإلغاء لا بعده مباشرةً في نفسِ النبضة: لو أُعيد التحميلُ
        //    قبل الإلغاء لأمكن للعاملِ أن يُعترض الطلبَ مرّةً أخرى.
        try {
            const windows = await self.clients.matchAll({ type: 'window' });
            for (const w of windows) {
                if ('navigate' in w) { try { await w.navigate(w.url); } catch (e) { /* تجاهل */ } }
            }
        } catch (e) { /* تجاهل */ }
    })());
});
